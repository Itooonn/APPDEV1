// Conditional Statements
let score = 87;
if (score >= 90) { 
    console.log("Your score is an A."); 
}
else if (score >= 80) { 
    console.log("Your score is a B."); 
}
else if (score >= 70) { 
    console.log("Your score is a C."); 
}
else { 
    console.log("Your score is an F."); 
}

// Looping through numbers 1 to 5
for (let i = 1; i <= 5; i++) { 
    console.log(i); 
}

